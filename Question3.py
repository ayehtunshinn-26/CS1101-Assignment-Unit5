# Question 3: Tuple Packing and Unpacking

# Packing values into a single tuple
book_info = ("Atomic Habits", "James Clear", 2018)

#Unpacking the tuple into variables
book_name, author_name, publication_year = book_info

#Display unpacked variable values
print("Book information:")
print("Book Name:", book_name)
print("Author Name:", author_name)
print("Publication Year:", publication_year)

